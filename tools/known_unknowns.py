#!/usr/bin/env python3
"""The known-unknowns list: every fact the boards rely on, verified or not.

Reads the review's per-domain JSON (docs/review-2/<domain>.json, the
`known_unknowns` rows) plus the hand-kept resolutions in
docs/review-2/resolutions.json, and writes docs/known-unknowns.md.

    python3 tools/known_unknowns.py            # write the page
    python3 tools/known_unknowns.py --check    # exit 1 if anything that could
                                               # stop a board is still open
    python3 tools/known_unknowns.py --check --tier plus   # an order of one tier:
                                               # facts marked open-ultra don't block it

`--check` is the order-step gate, and the score charges 100 for each open
fact it lists (docs/checks.md): nothing unverified that could stop a board
working may be open when the person orders. A fact about an Ultra-only part
can be marked open-ultra: it blocks an Ultra order but not a Lite or Plus one. A row is closed when it is
verified (source and date) or resolved (fixed in the design, or
justified with its margin) in resolutions.json, keyed "<domain>:<n>" by the
row's position in its domain's list.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REVIEW = ROOT / "docs" / "review-2"
DOMAINS = ["power", "audio", "digital", "thermal", "dfm", "parts"]


def rows():
    res = {}
    rp = REVIEW / "resolutions.json"
    if rp.is_file():
        res = json.loads(rp.read_text())
    for d in DOMAINS:
        p = REVIEW / f"{d}.json"
        if not p.is_file():
            continue
        for i, k in enumerate(json.loads(p.read_text()).get("known_unknowns", [])):
            key = f"{d}:{i}"
            r = res.get(key)
            status = k.get("status", "unverified")
            how = ""
            if r:
                status, how = r["status"], r["how"]
            yield key, d, k, status, how


def is_open(k, status, tier=None):
    if status == "open-ultra" and tier in ("lite", "plus"):
        return False
    board = k.get("board")
    if (tier == "lite" and board == "core") or (tier in ("plus", "ultra") and board == "lite-main"):
        return False
    return bool(k.get("could_stop_board")) and status not in ("verified", "resolved")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--tier", choices=["lite", "plus", "ultra"])
    a = ap.parse_args()
    all_rows = list(rows())
    open_rows = [r for r in all_rows if is_open(r[2], r[3], a.tier)]
    if a.check:
        for key, d, k, status, _ in open_rows:
            print(f"OPEN {key} [{k.get('board')}] {k.get('fact')}")
        print(f"{len(open_rows)} open of {len(all_rows)} facts")
        return 1 if open_rows else 0
    out = ["# Known unknowns: every fact the boards rely on", "",
           "Generated by `python3 tools/known_unknowns.py` from the first-spin",
           "review (docs/review-2/). `--check` fails while any fact that could stop",
           "a board is neither verified nor resolved; run it before ordering.", "",
           f"**{len(open_rows)} open** that could stop a board, of {len(all_rows)} facts.", ""]
    for title, sel in (("Open: could stop a board", lambda r: is_open(r[2], r[3])),
                       ("Closed or not board-stopping", lambda r: not is_open(r[2], r[3]))):
        out += [f"## {title}", "", "| Key | Board | Refs | Fact | Status | Source / how | Date | Stops board |",
                "|---|---|---|---|---|---|---|---|"]
        for key, d, k, status, how in all_rows:
            if not sel((key, d, k, status, how)):
                continue
            cell = lambda s: str(s or "").replace("|", "/").replace("\n", " ")
            out.append(f"| {key} | {cell(k.get('board'))} | {cell(', '.join(k.get('refs') or []))} | "
                       f"{cell(k.get('fact'))} | {status} | {cell(how or k.get('source'))} | "
                       f"{cell(k.get('date'))} | {'yes' if k.get('could_stop_board') else 'no'} |")
        out.append("")
    (ROOT / "docs" / "known-unknowns.md").write_text("\n".join(out) + "\n")
    print(f"wrote docs/known-unknowns.md: {len(open_rows)} open of {len(all_rows)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
