#!/usr/bin/env python3
"""Pack app/web for the firmware: every file gzipped, a size check, and a C
table the firmware links in, so the app is served from the image's own flash
with no filesystem partition.

    python3 app/build.py [--out app/dist]

Writes <out>/www/<file>.gz (for a LittleFS/SPIFFS image, if the firmware
prefers one) and <out>/webapp_files.c, a table of
{path, content_type, data, len}, every entry gzipped (send it with
Content-Encoding: gzip). Fails if the packed app is over BUDGET bytes. The
output is the same bytes every time (mtime 0), so a rebuild changes nothing.
"""
from __future__ import annotations

import argparse
import gzip
import sys
from pathlib import Path

APP = Path(__file__).resolve().parent
WEB = APP / "web"
# The firmware's spare room in its app partition is tight next to cspot,
# AirPlay and Bluetooth; 64 KB is the line agreed in docs/app.md.
BUDGET = 64 * 1024
TYPES = {".html": "text/html", ".js": "application/javascript", ".css": "text/css",
         ".webmanifest": "application/manifest+json", ".svg": "image/svg+xml", ".png": "image/png"}


def files() -> list[Path]:
    return sorted(p for p in WEB.iterdir() if p.is_file() and p.suffix in TYPES)


def pack(p: Path) -> bytes:
    return gzip.compress(p.read_bytes(), compresslevel=9, mtime=0)


def c_table(packed: list[tuple[Path, bytes]]) -> str:
    out = ["// Generated by app/build.py from app/web. Do not edit.",
           "// Every entry is gzipped: send it with Content-Encoding: gzip.",
           "#include <stddef.h>", "#include \"webapp_files.h\"", ""]
    for i, (p, data) in enumerate(packed):
        out.append(f"static const unsigned char f{i}[{len(data)}] = {{")
        for j in range(0, len(data), 20):
            out.append("  " + ",".join(str(b) for b in data[j:j + 20]) + ",")
        out.append("};")
    out.append("const webapp_file_t webapp_files[] = {")
    for i, (p, data) in enumerate(packed):
        out.append(f'  {{"/{p.name}", "{TYPES[p.suffix]}", f{i}, {len(data)}}},')
    out += ["};", f"const size_t webapp_files_count = {len(packed)};", ""]
    return "\n".join(out)


C_HEADER = """// Generated by app/build.py. The web app's files, gzipped.
#pragma once
#include <stddef.h>
typedef struct {
  const char *path;          // "/index.html"; serve "/" as "/index.html"
  const char *content_type;
  const unsigned char *data; // gzip
  size_t len;
} webapp_file_t;
extern const webapp_file_t webapp_files[];
extern const size_t webapp_files_count;
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=APP / "dist")
    o = ap.parse_args(argv)
    packed = [(p, pack(p)) for p in files()]
    (o.out / "www").mkdir(parents=True, exist_ok=True)
    for p, data in packed:
        (o.out / "www" / (p.name + ".gz")).write_bytes(data)
    (o.out / "webapp_files.c").write_text(c_table(packed))
    (o.out / "webapp_files.h").write_text(C_HEADER)
    total = sum(len(d) for _, d in packed)
    for p, d in packed:
        print(f"{p.name:24} {p.stat().st_size:7} -> {len(d):6}")
    print(f"{'total':24} {sum(p.stat().st_size for p, _ in packed):7} -> {total:6} (budget {BUDGET})")
    if total > BUDGET:
        print(f"over budget by {total - BUDGET} bytes", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
